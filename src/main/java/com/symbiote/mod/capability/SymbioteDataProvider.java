package com.symbiote.mod.capability;

import net.minecraft.core.Direction;
import net.minecraft.nbt.CompoundTag;
import net.minecraftforge.common.capabilities.Capability;
import net.minecraftforge.common.capabilities.ICapabilityProvider;
import net.minecraftforge.common.util.INBTSerializable;
import net.minecraftforge.common.util.LazyOptional;

import javax.annotation.Nonnull;
import javax.annotation.Nullable;

public class SymbioteDataProvider implements ICapabilityProvider, INBTSerializable<CompoundTag> {

    public static final net.minecraft.resources.ResourceLocation IDENTIFIER =
            new net.minecraft.resources.ResourceLocation(com.symbiote.mod.SymbioteMod.MOD_ID, "symbiote_data");

    private final SymbioteDataImpl data = new SymbioteDataImpl();
    private final LazyOptional<SymbioteData> optional = LazyOptional.of(() -> data);

    @Nonnull
    @Override
    public <T> LazyOptional<T> getCapability(@Nonnull Capability<T> cap, @Nullable Direction side) {
        return cap == ModCapabilities.SYMBIOTE_DATA ? optional.cast() : LazyOptional.empty();
    }

    @Override
    public CompoundTag serializeNBT() {
        return data.serializeNBT();
    }

    @Override
    public void deserializeNBT(CompoundTag nbt) {
        data.deserializeNBT(nbt);
    }

    public void invalidate() {
        optional.invalidate();
    }
}
